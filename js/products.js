function getCatalogCategory(product) {
  if (product.isCombo) return "Combos";
  if (product.sourcePage === 50) return "Cuidados faciais";
  if (product.sourcePage === 10 || product.sourcePage === 11) {
    return "Aromatização profissional";
  }
  if (product.sourcePage === 35) return "Essências";
  if (product.sourcePage === 36) return "Aromatizadores elétricos";
  if (product.sourcePage === 37) return "Sachês perfumados";
  if (product.sourcePage === 62) return "Embalagens";
  if (product.collection === "Aromaterapia") return "Aromaterapia";
  const name = product.name.toLocaleLowerCase("pt-BR");
  if (/body splash|colônia/.test(name)) return "Perfumaria";
  if (name.includes("refil")) return "Refis";
  if (name.includes("sabonete")) return "Sabonetes";
  if (name.includes("difusor") && !name.includes("aparelho difusor")) {
    return "Difusores";
  }
  if (
    /spray|água perfumada|perfume para roupas|perfume para ambientes|bruma/.test(
      name
    )
  ) {
    return "Sprays";
  }
  if (name.includes("vela")) return "Velas";
  if (product.category === "Aromaterapia") return "Aromaterapia";
  if (product.category === "Presentes" || name.includes("kit")) return "Presentes";
  if (product.category === "Acessórios") return "Acessórios";
  if (product.category === "Banho e corpo") return "Banho e corpo";
  return product.category || "Outros";
}

